/**
 * 把一段中文/中英文混合文本转成拼音首字母串（未收录的汉字不贡献字符，
 * 非中文字符原样透传，方便跟英文/数字型 SKU 编码一起搜）。
 */
export function pinyinInitials(text: string): string {
  let result = '';
  for (const ch of text) {
    const mapped = PINYIN_INITIAL_MAP[ch];
    if (mapped) {
      result += mapped;
    } else if (/[a-zA-Z0-9]/.test(ch)) {
      result += ch;
    }
  }
  return result;
}

/**
 * 搜索匹配：字面子串（大小写不限）或拼音首字母子串（大小写不限）任一命中即算匹配。
 * 空 query 视为始终匹配（用于“未输入时显示全部选项”场景）。
 */
export function matchesSearchText(query: string, text: string): boolean {
  const trimmedQuery = query.trim();
  if (!trimmedQuery) return true;
  if (!text) return false;
  const normalizedQuery = trimmedQuery.toLowerCase();
  if (text.toLowerCase().includes(normalizedQuery)) return true;
  return pinyinInitials(text).toLowerCase().includes(normalizedQuery);
}
