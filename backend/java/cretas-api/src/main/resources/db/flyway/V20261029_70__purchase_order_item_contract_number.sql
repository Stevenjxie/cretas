--
-- 客户(张权 2026-08-06 微信): 「这个下采购单的时候可以填写」, 指的是他 Excel 台账里的
-- 合同号那一列。
--
-- ## 为什么必须是行级, 单头那个不够
--   `purchase_orders.contract_number` 早就有(SP6 框架合同号), 但客户实际单据是
--   **同一张采购单两行、两个不同合同号**:
--     PO-20260806-0001
--       行1 牛外脊西冷MB2+谷饲100天  995.75 kg  合同号 SAN-16572
--       行2 牛外脊西冷MB2+谷饲100天 1010.65 kg  合同号 SAN-16562
--   单头只能放一个, 放哪个都是错的。
--
-- ## 与收货侧的关系
--   收货行(`purchase_receive_items.contract_number`)在 V20261029_61 已经有了 ——
--   也就是说数据最终能落对, 缺的只是「下单时就填、收货时自动带出」这个口子,
--   不然仓管要照着纸质合同重敲一遍。
--
-- 单头的 contract_number **保留不动**: 它是框架合同号, 与行级的具体合同号是两件事;
-- 行级为空时收货侧回落到单头(在 Java 侧做, 不在这里)。
-- =============================================================================

ALTER TABLE purchase_order_items
    ADD COLUMN IF NOT EXISTS contract_number varchar(64);

COMMENT ON COLUMN purchase_order_items.contract_number IS
    '行级合同号(客户纸质合同, 如 SAN-16572)。同一张采购单不同行可以不同; 为空时回落到 purchase_orders.contract_number';
